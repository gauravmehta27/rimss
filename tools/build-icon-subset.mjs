/**
 * Generates `src/styles/_icons.scss` containing only the Bootstrap Icons the app
 * actually renders, inlined as CSS `mask-image` data URIs.
 *
 * This replaces `bootstrap-icons/font/bootstrap-icons.css` (~97 kB of rules for
 * ~2000 icons) and its ~131 kB woff2 download with ~30 inlined glyphs.
 *
 * Run `npm run build:icons` after adding a new `bi-*` class to a template.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const iconDir = join(root, 'node_modules', 'bootstrap-icons', 'icons');
const outFile = join(root, 'src', 'styles', '_icons.scss');
const sourceDir = join(root, 'src');

/** Every `bi-foo` token that appears in a template, static or bound. */
function collectUsedIcons() {
  const used = new Set();
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) {
        walk(full);
        continue;
      }
      if (!['.html', '.ts'].includes(extname(entry))) continue;
      const content = readFileSync(full, 'utf8');
      for (const [, name] of content.matchAll(/\bbi-([a-z0-9]+(?:-[a-z0-9]+)*)\b/g)) {
        used.add(name);
      }
    }
  };
  walk(sourceDir);
  return [...used].sort();
}

/** Data URI for a mask-image: strip the fill so `currentColor` wins. */
function toMask(name) {
  const svg = readFileSync(join(iconDir, `${name}.svg`), 'utf8')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s*fill="currentColor"/g, '')
    .replace(/\s*class="[^"]*"/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  // encodeURIComponent escapes `'`, so single quotes are safe here (and match Prettier).
  return `url('data:image/svg+xml,${encodeURIComponent(svg)}')`;
}

const icons = collectUsedIcons();
const missing = [];
const rules = [];

for (const name of icons) {
  try {
    rules.push(`.bi-${name} {\n  --bi: ${toMask(name)};\n}`);
  } catch {
    missing.push(name);
  }
}

if (missing.length) {
  console.warn(`Skipped tokens with no matching icon: ${missing.join(', ')}`);
}

const output = `/* Generated by \`npm run build:icons\` — do not edit by hand. */

.bi {
  display: inline-block;
  width: 1em;
  height: 1em;
  flex-shrink: 0;
  vertical-align: -0.125em;
  background-color: currentcolor;
  mask: var(--bi) no-repeat center / contain;
  -webkit-mask: var(--bi) no-repeat center / contain;
}

${rules.join('\n\n')}
`;

writeFileSync(outFile, output, 'utf8');
console.log(`Wrote ${rules.length} icons to src/styles/_icons.scss`);
